"""Fail-closed tests for the V26C J14 post-mismatch DAgger dataset.

Hermetic: the authorised leaf is never created. Every write path is exercised in a temporary root
through OUTPUT_ROOT_OVERRIDE. No rollout, no fit, no environment, and torch is never imported -
by the runner OR by this suite.

NOT BORN SPENT: the preflight-GO and leaf-absence assertions are CONDITIONAL on the leaf, so this
suite still runs as evidence after J14 commits.
"""
