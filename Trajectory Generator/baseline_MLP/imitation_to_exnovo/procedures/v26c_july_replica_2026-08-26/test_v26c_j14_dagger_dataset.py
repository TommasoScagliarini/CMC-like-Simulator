HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
# NO BYTECODE, SET BEFORE THE IMPORT BELOW. Importing the runner would otherwise write or refresh
# a .pyc under the validation root - before the guard is installed and before the opening snapshot
# is taken, so the write would be invisible to both. Setting this here is what makes the "not one
# byte" claim SELF-CONTAINED instead of dependent on PYTHONDONTWRITEBYTECODE being exported by
# whoever launches the suite.
sys.dont_write_bytecode = True
