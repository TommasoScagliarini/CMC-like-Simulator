TEST_SRC = HERE.joinpath(Path(__file__).name).read_text()
# the pristine write primitives, captured at import time, before any guard exists
J14_PRISTINE = {"open": builtins.open, "io_open": io.open, "path_open": Path.open,
                "os_open": os.open}

CHECKS = 0


def check(c, w):
    global CHECKS
    assert c, w
    CHECKS += 1


def expect(fn, exc, w):
    global CHECKS
    try:
        fn()
    except exc as e:
        CHECKS += 1
        return e
    raise AssertionError(f"expected {exc.__name__}: {w}")


def snapshot(root: Path) -> dict[str, str]:
    """EVERY regular file under root, hashed. NO EXCLUSION - __pycache__ is inside the guarded
    set, because generated bytecode is still a byte written under the validation root."""
    out: dict[str, str] = {}
    for p in sorted(root.rglob("*")):
        if p.is_file():
            out[str(p.relative_to(root))] = hashlib.sha256(p.read_bytes()).hexdigest()
    return out


# ================================================================ hermeticity ====================
# NOT ONE BYTE may be written, unlinked, renamed or removed under the real validation root while
# this suite runs. A `finally` that restores an artefact is NOT good enough: an interrupted suite
# would leave a frozen artefact corrupted or a source leaf marked invalid. So every negative test
# operates on a TEMPORARY MIRROR, and this guard makes the rule enforceable rather than a promise.

MIRROR: Path
ATTEMPTS: list[str] = []
_ALLOWED_ROOTS: list[Path] = []


def _under_here(target) -> bool:
    try:
        p = Path(os.fspath(target))
    except TypeError:
        return False
    p = p if p.is_absolute() else Path.cwd() / p
    try:
        p.resolve().relative_to(HERE.resolve())
    except (ValueError, OSError):
        return False
    for allowed in _ALLOWED_ROOTS:
        try:
            p.resolve().relative_to(allowed.resolve())
            return False
        except (ValueError, OSError):
            continue
    return True


class HermeticGuard:
    """Fail-closed: any write primitive aimed under HERE raises instead of touching the file."""

    _PATH_METHODS = ("write_text", "write_bytes", "mkdir", "unlink", "rmdir", "touch", "rename",
                     "replace", "symlink_to", "hardlink_to", "chmod")
    _OS_FUNCS = ("rename", "replace", "remove", "unlink", "mkdir", "makedirs", "rmdir", "truncate")

    def __enter__(self):
        self._path = {n: getattr(Path, n, None) for n in self._PATH_METHODS}
        self._os = {n: getattr(os, n, None) for n in self._OS_FUNCS}
        self._misc = {"open": builtins.open, "io_open": io.open, "path_open": Path.open,
                      "os_open": os.open,
                      "rmtree": shutil.rmtree, "copyfile": shutil.copyfile,
                      "copy2": shutil.copy2, "move": shutil.move,
                      "savez": np.savez, "savez_compressed": np.savez_compressed}

        def block(label, real, path_arg=0, is_method=False):
            def f(*a, **k):
                # An fd-relative call (dir_fd=) carries a BARE NAME, not a path: resolving it
                # against cwd would flag shutil.rmtree's own internal unlinks as violations even
                # when the tree being removed is in the temp root. Such calls are therefore
                # DELEGATED UNCHECKED. Scope of that exemption, stated narrowly and no wider:
                # this suite makes no direct fd-relative call (asserted by AST in _body), and the
                # only code reaching this branch is shutil.rmtree's own descent, whose entry point
                # is itself guarded. This is NOT a claim that fd-relative writes are covered in
                # general - an fd-relative write from code outside this suite would pass through.
                if k.get("dir_fd") is not None:
                    return real(*a, **k)
                target = a[0] if is_method else (a[path_arg] if len(a) > path_arg else None)
                if target is not None and _under_here(target):
                    ATTEMPTS.append(f"{label}({target})")
                    raise AssertionError(f"HERMETICITY VIOLATION: {label} aimed at {target}, "
                                         f"which is under the real validation root")
                return real(*a, **k)
            return f

        for n, real in self._path.items():
            if real is not None:
                setattr(Path, n, block(f"Path.{n}", real, is_method=True))
        for n, real in self._os.items():
            if real is not None:
                setattr(os, n, block(f"os.{n}", real))
        shutil.rmtree = block("shutil.rmtree", self._misc["rmtree"])
        shutil.copyfile = block("shutil.copyfile", self._misc["copyfile"], path_arg=1)
        shutil.copy2 = block("shutil.copy2", self._misc["copy2"], path_arg=1)
        shutil.move = block("shutil.move", self._misc["move"], path_arg=1)
        np.savez = block("np.savez", self._misc["savez"])
        np.savez_compressed = block("np.savez_compressed", self._misc["savez_compressed"])

        real_open, real_os_open = self._misc["open"], self._misc["os_open"]

        def guarded_open(file, mode="r", *a, **k):
            if any(c in mode for c in "wax+") and _under_here(file):
                ATTEMPTS.append(f"open({file}, {mode!r})")
                raise AssertionError(f"HERMETICITY VIOLATION: open({file}, {mode!r}) under the "
                                     f"real validation root")
            return real_open(file, mode, *a, **k)

        def guarded_os_open(path, flags, *a, **k):
            writing = flags & (os.O_WRONLY | os.O_RDWR | os.O_CREAT | os.O_APPEND | os.O_TRUNC)
            if writing and _under_here(path):
                ATTEMPTS.append(f"os.open({path}, write)")
                raise AssertionError(f"HERMETICITY VIOLATION: os.open({path}) for writing under "
                                     f"the real validation root")
            return real_os_open(path, flags, *a, **k)

        # io.open and builtins.open are the SAME object on CPython, but pathlib captured the
        # original at class-definition time (3.10: _NormalAccessor.open = io.open), so patching
        # io.open does NOT reach Path.open. Both are patched, and each has its own probe.
        real_path_open = self._misc["path_open"]

        def guarded_path_open(self, mode="r", *a, **k):
            if any(c in mode for c in "wax+") and _under_here(self):
                ATTEMPTS.append(f"Path.open({self}, {mode!r})")
                raise AssertionError(f"HERMETICITY VIOLATION: Path.open({self}, {mode!r}) under "
                                     f"the real validation root")
            return real_path_open(self, mode, *a, **k)

        builtins.open, io.open, os.open = guarded_open, guarded_open, guarded_os_open
        Path.open = guarded_path_open
        return self

    def __exit__(self, *exc):
        for n, real in self._path.items():
            if real is not None:
                setattr(Path, n, real)
        for n, real in self._os.items():
            if real is not None:
                setattr(os, n, real)
        builtins.open, os.open = self._misc["open"], self._misc["os_open"]
        io.open, Path.open = self._misc["io_open"], self._misc["path_open"]
        shutil.rmtree, shutil.copyfile = self._misc["rmtree"], self._misc["copyfile"]
        shutil.copy2, shutil.move = self._misc["copy2"], self._misc["move"]
        np.savez, np.savez_compressed = self._misc["savez"], self._misc["savez_compressed"]
        return False


# the three trace files are 51 MB each and are never tampered, so they are symlinked rather than
# copied. Everything a negative test may touch is a REAL, INDEPENDENT copy.
NEVER_TAMPERED = ("j12_cell_A_trace.json", "j12_cell_E_trace.json", "j12_cell_F_trace.json")


def build_mirror(tmp: Path) -> Path:
    """A temporary mirror of every pinned source, plus both preregistrations."""
    mirror = tmp / "mirror"
    wanted = list(J14.PIN_SOURCES) + [J14.PREREG.name, J14.SUPERSEDED_PREREG.name]
    for rel in wanted:
        src, dst = HERE / rel, mirror / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        if src.name in NEVER_TAMPERED:
            dst.symlink_to(src)
        else:
            shutil.copyfile(src, dst)
    return mirror


class use_mirror:
    """Point every module constant at the mirror; restore only Python references afterwards."""

    NAMES = ("HERE", "PREREG", "SUPERSEDED_PREREG", "J12_LEAF", "J1_LEAF", "J7_LEAF",
             "J10R1_LEAF", "J11_LEAF", "J11_AGGREGATE", "J2_MODULE")

    def __init__(self, mirror: Path):
        self.mirror = mirror

    def __enter__(self):
        self.saved = {n: getattr(J14, n) for n in self.NAMES}
        rel = {n: getattr(J14, n).relative_to(HERE) for n in self.NAMES if n != "HERE"}
        J14.HERE = self.mirror
        for n, r in rel.items():
            setattr(J14, n, self.mirror / r)
        return self.mirror

    def __exit__(self, *exc):
        for n, v in self.saved.items():
            setattr(J14, n, v)
        return False


def reset_mirror(mirror: Path) -> None:
    """Rebuild the mirror from the real sources. Only ever writes inside the temp root."""
    shutil.rmtree(mirror, ignore_errors=True)
    build_mirror(mirror.parent)


def main() -> int:
    global MIRROR
    tmproot = Path(tempfile.mkdtemp(prefix="v26c_j14_hermetic_"))
    _ALLOWED_ROOTS.append(tmproot)
    MIRROR = build_mirror(tmproot)
    try:
        with HermeticGuard():
            return _body(tmproot)
    finally:
        shutil.rmtree(tmproot, ignore_errors=True)
        _ALLOWED_ROOTS.clear()


